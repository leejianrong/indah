#!/usr/bin/env bash
# Assemble the single-app demo gallery for Fly.io (ADR-0023) into build/.
#
# One Docker image serves every demo behind a sub-path (gallery_app.py mounts each
# example's indah app under /<slug> and a gallery index at /). Copies gallery_app.py
# + the demo example files + writes the Dockerfile/requirements/fly.toml. Does NOT
# deploy (see deploy_fly.sh / README.md).
set -euo pipefail

here="$(cd "$(dirname "$0")" && pwd)"
repo="$(cd "$here/../.." && pwd)"
out="$here/build"
app="${FLY_APP:-indah-demos}"
region="${FLY_REGION:-sin}"

# Example modules the gallery mounts (must cover every hosted entry's module in gallery.toml).
examples=(chatbot training_dashboard diffusion poster upload_classify object_detection charts stocks dataframe_explorer prettymap map_poster grc_map audio_analysis gpx_viewer markov_poet sorting)

# Install the published wheel from PyPI (the python:3.12-slim base has no git, and a
# PyPI install is what a user would run). It is pinned to this checkout's version, not a
# range: with ">=" Docker reuses the cached pip layer, so the image kept an old release
# while the demos copied in beside it used newer API (gpx-viewer broke on a pre-0.3.0
# indah, IND-167). Deploy after the release is on PyPI.
INDAH_VERSION="$(sed -n 's/^version = "\(.*\)"/\1/p' "$repo/pyproject.toml" | head -1)"

# The demo libraries (numpy, pillow, onnxruntime, huggingface_hub, matplotlib) come from the
# `indah[demos]` extra (ADR-0042, IND-188) once the pinned release provides it. A release that
# predates the extra (0.7.0 and older) would install `indah[demos]` WITHOUT the libraries (pip only
# warns about an unknown extra), so the script asks PyPI and, if the extra is missing or PyPI cannot
# be reached, falls back to naming the libraries here. Delete the fallback when 0.8.0 or later is
# the oldest release anyone deploys.
DEMO_LIBS=(numpy pillow onnxruntime huggingface_hub matplotlib)
if python3 - "$INDAH_VERSION" <<'PY'
import json, sys, urllib.request
try:
    url = f"https://pypi.org/pypi/indah/{sys.argv[1]}/json"
    with urllib.request.urlopen(url, timeout=15) as r:
        requires = json.load(r)["info"].get("requires_dist") or []
except Exception:
    sys.exit(1)
sys.exit(0 if any("extra == 'demos'" in x or 'extra == "demos"' in x for x in requires) else 1)
PY
then
  INDAH_REQ="indah[demos]==$INDAH_VERSION"
  EXTRA_LIBS=()
else
  echo "note: indah $INDAH_VERSION on PyPI does not provide the 'demos' extra (or PyPI is unreachable); naming the demo libraries instead" >&2
  INDAH_REQ="indah==$INDAH_VERSION"
  EXTRA_LIBS=("${DEMO_LIBS[@]}")
fi

rm -rf "$out"
mkdir -p "$out"
cp "$here/gallery_app.py" "$out/"
cp "$here/gallery_catalog.py" "$here/gallery_health.py" "$here/gallery.toml" "$out/"  # the catalog and its loader
cp "$here/landing.html" "$out/"   # the landing-page template gallery_app.py reads
# The link-check status for listed apps (IND-192), if one is present. Fetch the latest first:
#   git fetch origin gallery-status && git show FETCH_HEAD:gallery_status.json > deploy/fly/gallery_status.json
# Without it every listed card shows.
[ -f "$here/gallery_status.json" ] && cp "$here/gallery_status.json" "$out/"
cp -r "$here/thumbnails" "$out/"  # real per-demo screenshots for the gallery cards
for mod in "${examples[@]}"; do
  cp "$repo/examples/$mod.py" "$out/$mod.py"
done

{
  echo "$INDAH_REQ"
  echo "uvicorn[standard]"
  for lib in "${EXTRA_LIBS[@]+"${EXTRA_LIBS[@]}"}"; do echo "$lib"; done
} > "$out/requirements.txt"

cat > "$out/Dockerfile" <<'DOCKER'
FROM python:3.12-slim
ENV PYTHONUNBUFFERED=1
WORKDIR /app
COPY requirements.txt .
RUN pip install --no-cache-dir -r requirements.txt
# Fetch both ONNX models now, so the first visitor does not wait on (or fail on) a download
# while the page says "connecting". The same default cache is read at run time.
RUN python -c "from huggingface_hub import hf_hub_download as d; d('onnxmodelzoo/mobilenetv2-12', 'mobilenetv2-12.onnx'); d('onnxmodelzoo/ssd_mobilenet_v1_12', 'ssd_mobilenet_v1_12.onnx')"
COPY . .
EXPOSE 7860
# One app mounts every demo under /<slug>; --factory builds it (imports the examples).
CMD ["uvicorn", "gallery_app:create_gallery", "--factory", "--host", "0.0.0.0", "--port", "7860"]
DOCKER

cat > "$out/fly.toml" <<TOML
# Generated by deploy/fly/build_gallery.sh - do not edit by hand.
app = "$app"
primary_region = "$region"

[build]
  dockerfile = "Dockerfile"

[http_service]
  internal_port = 7860
  force_https = true
  auto_stop_machines = "stop"
  auto_start_machines = true
  min_machines_running = 0

  # Bound simultaneous SSE connections on this one machine (deploy_fly.sh runs with
  # --ha=false, so Fly never provisions a second machine under load - this is what
  # keeps a connection flood from OOMing the box instead). ADR-0024.
  [http_service.concurrency]
    type = "connections"
    soft_limit = 20
    hard_limit = 25

[[vm]]
  size = "shared-cpu-1x"
  memory = "1gb"
TOML

echo "built $out/ (app=$app, region=$region, ${#examples[@]} demos)"
