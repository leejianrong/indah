_LANDING = (Path(__file__).parent / "landing.html").read_text(encoding="utf-8")


def _index_html(demos: list[dict[str, Any]]) -> str:
    cards = "".join(_card(d) for d in demos)
    return (
        _LANDING.replace("%%FAVICON%%", _FAVICON_URI)
        .replace("%%LOGO_NAV%%", _mark(26))
        .replace("%%LOGO_HERO%%", _mark(64))
        .replace("%%CARDS%%", cards)
        .replace("%%COMPARE%%", _COMPARE)
        .replace("%%GITHUB%%", GITHUB_URL)
        .replace("%%DOCS%%", DOCS_URL)
    )


def _fly_client_ip(scope: Scope) -> str:
    """The client address on Fly: ``Fly-Client-IP`` (set by Fly's edge, which overwrites any
    client-supplied value) first, else the socket peer. ``X-Forwarded-For`` is not read: a
    client can send anything in it (ADR-0037)."""
    fly_ip = dict(scope.get("headers") or []).get(b"fly-client-ip")
    return fly_ip.decode("latin-1") if fly_ip else peer_address(scope)


def build_gallery(demos: list[dict[str, Any]]) -> ASGIApp:
    """Mount each demo app under `/<slug>` and serve a gallery index at `/`.

    ``demos`` is a list of ``{"slug","title","emoji","app"}`` (``app`` is an ASGI app).
    """

    async def index(_request):
        return HTMLResponse(_index_html(demos))

    routes: list[Any] = [Mount(f"/{d['slug']}", app=d["app"]) for d in demos]
    if THUMB_DIR.is_dir():
        routes.append(Mount("/thumbnails", app=StaticFiles(directory=THUMB_DIR)))
    routes.append(Route("/", index))
    app: ASGIApp = Starlette(routes=routes)
    limited = RateLimitMiddleware(app, Limits.public().rate or {}, client_ip=_fly_client_ip)
    return SecurityHeadersMiddleware(limited)


# The demo sources on GitHub, so each demo's "Source" link points at its own file.
SOURCE_BASE = "https://github.com/leejianrong/indah/blob/main/examples"

# Session bounds for the public deployment only (ADR-0024) - every other user of
# InMemorySessionStore (notebooks, tests) keeps the unbounded default.
_PUBLIC_MAX_SESSIONS = Limits.public().max_sessions
_PUBLIC_SESSION_IDLE_TIMEOUT_SECONDS = Limits.public().session_idle_seconds


def apply_public_session_limits(app: ASGIApp) -> None:
    """Bound an example's session store for the public deployment (ADR-0024).

    A no-op for any store that isn't ``InMemorySessionStore`` (e.g. a future
    external backend, or an example built with ``session=`` instead of
    ``session_factory=``). Split out from ``create_gallery`` so it is
    unit-testable without importing every example's (sometimes heavy) deps.
    """
    store = app.state.store
    if isinstance(store, InMemorySessionStore):
        store.max_sessions = _PUBLIC_MAX_SESSIONS
        store.idle_timeout_seconds = _PUBLIC_SESSION_IDLE_TIMEOUT_SECONDS


def create_gallery() -> ASGIApp:
    """Import the example modules and build the gallery (used in the deploy image)."""
    demos = []
    for slug, title, emoji, module in MANIFEST:
        mod = importlib.import_module(module)
        # Per-demo page chrome (read by the shell's _index): a distinct tab title, a
        # clickable logo back to the gallery ("../" resolves from /<slug>/ to /), and a
        # link to this demo's source. The mounted sub-app carries its own app.state.
        mod.app.state.page_title = title
        mod.app.state.home_url = "../"
        mod.app.state.source_url = f"{SOURCE_BASE}/{module}.py"
        apply_public_session_limits(mod.app)
        demos.append({"slug": slug, "title": title, "emoji": emoji, "app": mod.app})
    return build_gallery(demos)
