"""One ASGI app that hosts every indah demo behind sub-paths (ADR-0023, Fly.io).

A single Starlette app mounts each demo's indah app under `/<slug>` and serves a
gallery index at `/`. This works because the indah shell uses document-relative URLs
(`api/stream`, `api/event`, ...) so it survives a base path - the same property that
makes it run behind Colab's and Runpod's proxies (ADR-0001). One machine, one domain
(`.../poster`, `.../chatbot`, ...), and it dogfoods indah's single-port/base-path
design.

Run in the deploy image with uvicorn's factory mode:
    uvicorn gallery_app:create_gallery --factory --host 0.0.0.0 --port 7860

`build_gallery` is pure (imports only Starlette) so it is unit-testable without the
examples; `create_gallery` imports the example modules (present in the deploy image).
"""

from __future__ import annotations

import base64
import html
import importlib
from pathlib import Path
from typing import Any

import gallery_health
from gallery_catalog import CATALOG, THUMB_DIR, hosted, load_catalog, validate_catalog
from gallery_catalog import listed as listed_entries
from starlette.applications import Starlette
from starlette.responses import HTMLResponse
from starlette.routing import Mount, Route
from starlette.staticfiles import StaticFiles
from starlette.types import ASGIApp, Scope

from indah.hardening import Limits, RateLimitMiddleware, SecurityHeadersMiddleware, peer_address
from indah.session_store import InMemorySessionStore

# The cards come from gallery.toml (see gallery_catalog.py). THUMB_DIR holds the real per-demo
# screenshots (generated by scripts/capture_thumbnails.py); a card with no PNG there falls back to
# a gradient tile.

# The Bunga mark (two magenta petals, two teal), inlined so the gallery needs no assets.
_BUNGA = (
    '<path d="M16 16C11.7 12.4 11.7 6 16 3.6C20.3 6 20.3 12.4 16 16Z" fill="#b5296b"/>'
    '<path d="M16 16C20.3 19.6 20.3 26 16 28.4C11.7 26 11.7 19.6 16 16Z" fill="#b5296b"/>'
    '<path d="M16 16C12.4 20.3 6 20.3 3.6 16C6 11.7 12.4 11.7 16 16Z" fill="#2e6d62"/>'
    '<path d="M16 16C19.6 20.3 26 20.3 28.4 16C26 11.7 19.6 11.7 16 16Z" fill="#2e6d62"/>'
)
_FAVICON_SVG = f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 32 32">{_BUNGA}</svg>'
_FAVICON_URI = "data:image/svg+xml;base64," + base64.b64encode(_FAVICON_SVG.encode()).decode()
GITHUB_URL = "https://github.com/leejianrong/indah"
DOCS_URL = "https://indah.abangai.dev/docs/"


def _mark(size: int) -> str:
    return (
        f'<svg class="mark" width="{size}" height="{size}" viewBox="0 0 32 32" '
        f'role="img" aria-label="indah">{_BUNGA}</svg>'
    )


def _thumb(d: dict[str, Any]) -> str:
    title = html.escape(d["title"])
    name = d.get("thumbnail") or f"{d['slug']}.png"
    if (THUMB_DIR / name).is_file():
        # A real screenshot (relative src, so it resolves under any base path).
        return (
            f'<span class="thumb"><img class="thumb-img" src="thumbnails/{html.escape(name)}" '
            f'alt="{title} preview" loading="lazy"></span>'
        )
    return (
        '<span class="thumb"><span class="thumb-dots"></span>'
        f'<span class="thumb-emoji">{html.escape(d.get("emoji", ""))}</span></span>'
    )


def _card(d: dict[str, Any]) -> str:
    slug = html.escape(d["slug"])
    title = html.escape(d["title"])
    blurb = html.escape(d.get("blurb", ""))
    # Relative link (trailing slash) so it resolves under any base path.
    return (
        f'<a class="card" href="{slug}/">{_thumb(d)}'
        f'<span class="card-body"><span class="card-title">{title}</span>'
        f'<span class="card-blurb">{blurb}</span></span></a>'
    )


def _listed_card(d: dict[str, Any]) -> str:
    """A card for an app someone else hosts: it links out and the gallery runs nothing. Never an
    iframe, and ``noopener noreferrer`` so the other site gets no handle on this page."""
    title = html.escape(d["title"])
    blurb = html.escape(d.get("blurb", ""))
    author = html.escape(d.get("author", ""))
    tag = (
        '<span class="card-tag">Not responding</span>'
        if d.get("status") == "not_responding"
        else ""
    )
    return (
        f'<a class="card" href="{html.escape(d["url"], quote=True)}" target="_blank" '
        f'rel="noopener noreferrer">{_thumb(d)}'
        f'<span class="card-body"><span class="card-title">{title}</span>{tag}'
        f'<span class="card-blurb">{blurb}</span>'
        f'<span class="card-blurb">External app by {author}</span></span></a>'
    )


# The comparison table lives on the landing page (not the docs). Framed to indah's
# strengths, but honest about what each row means.
_COMPARE = """
<tr><th scope="row">Reactive updates (no full-script rerun)</th>
  <td class="col-indah">Yes</td><td class="no">Reruns the script</td>
  <td class="mid">Event callbacks</td><td class="yes">Yes</td></tr>
<tr><th scope="row">No Node build at install or runtime</th>
  <td class="col-indah">Yes</td><td class="yes">Yes</td><td class="yes">Yes</td>
  <td class="no">Needs a Node build</td></tr>
<tr><th scope="row">Single port, notebook-proxy friendly</th>
  <td class="col-indah">Yes (SSE + POST)</td><td class="mid">WebSocket</td>
  <td class="mid">WebSocket</td><td class="mid">WebSocket</td></tr>
<tr><th scope="row">Token / point streaming built in</th>
  <td class="col-indah">Yes</td><td class="mid">Limited</td>
  <td class="yes">Yes</td><td class="mid">Limited</td></tr>
<tr><th scope="row">Runs inside a throwaway Colab / Runpod container</th>
  <td class="col-indah">Yes</td><td class="mid">Often</td>
  <td class="mid">Often</td><td class="no">Build step breaks</td></tr>
"""


_LANDING = (Path(__file__).parent / "landing.html").read_text(encoding="utf-8")


def _index_html(demos: list[dict[str, Any]], outside: list[dict[str, Any]]) -> str:
    cards = "".join(_card(d) for d in demos) + "".join(_listed_card(d) for d in outside)
    return (
        _LANDING.replace("%%FAVICON%%", _FAVICON_URI)
        .replace("%%LOGO_NAV%%", _mark(26))
        .replace("%%LOGO_HERO%%", _mark(64))
        .replace("%%CARDS%%", cards)
        .replace("%%COMPARE%%", _COMPARE)
        .replace("%%GITHUB%%", GITHUB_URL)
        .replace("%%DOCS%%", DOCS_URL)
    )


def _fly_client_ip(scope: Scope) -> str:
    """The client address on Fly: ``Fly-Client-IP`` (set by Fly's edge, which overwrites any
    client-supplied value) first, else the socket peer. ``X-Forwarded-For`` is not read: a
    client can send anything in it (ADR-0037)."""
    fly_ip = dict(scope.get("headers") or []).get(b"fly-client-ip")
    return fly_ip.decode("latin-1") if fly_ip else peer_address(scope)


def build_gallery(
    demos: list[dict[str, Any]],
    listed: list[dict[str, Any]] | None = None,
    status: dict[str, Any] | None = None,
) -> ASGIApp:
    """Mount each demo app under `/<slug>` and serve a gallery index at `/`.

    ``demos`` is a list of ``{"slug","title","emoji","blurb","app"}`` (``app`` is an ASGI app).
    ``listed`` holds catalog entries for apps hosted elsewhere; they get a card that links out.
    ``status`` is the link-check state (``gallery_health``); no network call is made here.
    """
    # Listed apps: the weekly link check's status decides what shows (hidden ones are left out).
    outside = gallery_health.apply_status(listed or [], status or {})

    async def index(_request):
        return HTMLResponse(_index_html(demos, outside))

    routes: list[Any] = [Mount(f"/{d['slug']}", app=d["app"]) for d in demos]
    if THUMB_DIR.is_dir():
        routes.append(Mount("/thumbnails", app=StaticFiles(directory=THUMB_DIR)))
    routes.append(Route("/", index))
    app: ASGIApp = Starlette(routes=routes)
    limited = RateLimitMiddleware(app, Limits.public().rate or {}, client_ip=_fly_client_ip)
    return SecurityHeadersMiddleware(limited)


# The demo sources on GitHub, so each demo's "Source" link points at its own file.
SOURCE_BASE = "https://github.com/leejianrong/indah/blob/main/examples"

# Session bounds for the public deployment only (ADR-0024) - every other user of
# InMemorySessionStore (notebooks, tests) keeps the unbounded default.
_PUBLIC_MAX_SESSIONS = Limits.public().max_sessions
_PUBLIC_SESSION_IDLE_TIMEOUT_SECONDS = Limits.public().session_idle_seconds


def apply_public_session_limits(app: ASGIApp) -> None:
    """Bound an example's session store for the public deployment (ADR-0024).

    A no-op for any store that isn't ``InMemorySessionStore`` (e.g. a future
    external backend, or an example built with ``session=`` instead of
    ``session_factory=``). Split out from ``create_gallery`` so it is
    unit-testable without importing every example's (sometimes heavy) deps.
    """
    store = app.state.store
    if isinstance(store, InMemorySessionStore):
        store.max_sessions = _PUBLIC_MAX_SESSIONS
        store.idle_timeout_seconds = _PUBLIC_SESSION_IDLE_TIMEOUT_SECONDS


def create_gallery() -> ASGIApp:
    """Import the hosted examples named in ``gallery.toml`` and build the gallery (deploy image)."""
    entries = load_catalog(CATALOG)
    problems = validate_catalog(entries)
    if problems:
        raise RuntimeError("gallery.toml is invalid: " + "; ".join(problems))
    demos = []
    for e in hosted(entries):
        mod = importlib.import_module(e["module"])
        # Per-demo page chrome (read by the shell's _index): a distinct tab title, a
        # clickable logo back to the gallery ("../" resolves from /<slug>/ to /), and a
        # link to this demo's source. The mounted sub-app carries its own app.state.
        mod.app.state.page_title = e["title"]
        mod.app.state.home_url = "../"
        mod.app.state.source_url = e.get("source_url") or f"{SOURCE_BASE}/{e['module']}.py"
        apply_public_session_limits(mod.app)
        demos.append({**e, "app": mod.app})
    return build_gallery(demos, listed_entries(entries), gallery_health.load_state())
