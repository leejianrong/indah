#!/usr/bin/env python3
"""Refresh src/indah/cloudflare_ips.py from Cloudflare's published ranges (IND-204).

Run this by hand, read the diff, commit it. indah never fetches the list at run time: a list
that changed under a running app would change who it believes. The unit test
``test_the_vendored_cloudflare_list_is_not_older_than_a_year`` fails when the file is stale.

    python scripts/refresh_cloudflare_ips.py            # writes the file
    python scripts/refresh_cloudflare_ips.py --check    # exits 1 if the published list differs
"""

from __future__ import annotations

import argparse
import ipaddress
import sys
from datetime import date
from pathlib import Path
from urllib.request import Request, urlopen

BASE = "https://www.cloudflare.com/ips"
TARGET = Path(__file__).resolve().parents[1] / "src" / "indah" / "cloudflare_ips.py"

TEMPLATE = '''"""Cloudflare's edge ranges, for ``trusted_proxies=["cloudflare"]`` (IND-204).

Source: {source}
Fetched: {fetched}

This file is generated by ``scripts/refresh_cloudflare_ips.py``; indah never fetches it at run
time. Cloudflare changes the list rarely: refresh, read the diff and commit. A unit test fails
when the file is more than a year old.
"""

SOURCE = "{source}"
FETCHED = "{fetched}"

IPV4 = [
{v4}
]

IPV6 = [
{v6}
]
'''


def fetch(kind: str) -> list[str]:
    # Cloudflare answers 403 to urllib's default User-Agent, so say who is asking.
    request = Request(f"{BASE}-{kind}", headers={"User-Agent": "indah-refresh-cloudflare-ips/1"})
    with urlopen(request, timeout=20) as response:  # noqa: S310 - fixed https URL
        text = response.read().decode("ascii")
    entries = [line.strip() for line in text.splitlines() if line.strip()]
    for entry in entries:
        net = ipaddress.ip_network(entry)  # strict: raises on a malformed or host-bit entry
        if net.prefixlen == 0:
            raise SystemExit(f"refusing {entry!r} from {BASE}-{kind}: it would trust everything")
    if not entries:
        raise SystemExit(f"{BASE}-{kind} returned nothing")
    return entries


def render(v4: list[str], v6: list[str], fetched: str) -> str:
    return TEMPLATE.format(
        source=f"{BASE}-v4 and {BASE}-v6",
        fetched=fetched,
        v4="\n".join(f'    "{e}",' for e in v4),
        v6="\n".join(f'    "{e}",' for e in v6),
    )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="compare, do not write")
    args = parser.parse_args()
    v4, v6 = fetch("v4"), fetch("v6")
    if args.check:
        sys.path.insert(0, str(TARGET.parent.parent))
        from indah import cloudflare_ips  # noqa: PLC0415

        same = list(cloudflare_ips.IPV4) == v4 and list(cloudflare_ips.IPV6) == v6
        print("up to date" if same else "the published list differs: run without --check")
        return 0 if same else 1
    TARGET.write_text(render(v4, v6, date.today().isoformat()))
    print(f"wrote {TARGET} ({len(v4)} IPv4 and {len(v6)} IPv6 ranges)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
